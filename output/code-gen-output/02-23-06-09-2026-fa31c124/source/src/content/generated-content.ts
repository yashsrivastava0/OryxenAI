export type ApprovedContentId = typeof CONTENT_INDEX[number]["content_id"];
export function contentForRoute(routeId: string): PublicContentPack | undefined {
  return PUBLIC_CONTENT.find((item) => item.route_id === routeId);
}

export function sectionForRoute(routeId: string, sectionId: string) {
  return contentForRoute(routeId)?.sections.find((item) => item.section_id === sectionId);
}

export function contentValue(contentId: ApprovedContentId): string {
  const entry = CONTENT_INDEX.find((item) => item.content_id === contentId);
  if (!entry || typeof entry.value !== "string") throw new Error(`Unknown approved content key: ${contentId}`);
  return entry.value;
}
