def _build_profile(reasoning_effort: str = "") -> Any:
    settings = get_settings()
    profile = settings.models.get_profile("discovery")
    assert profile is not None, "Missing [profiles.discovery]"
    if reasoning_effort:
        profile.reasoning_effort = reasoning_effort
    return profile


def _synthetic_instructions(case: dict[str, str]) -> str:
    from oryxenai.agents.discovery.prompt_builder import build_instructions

    source_packet = {
        "main_prompt": case.get("prompt", ""),
        "resume_text": case.get("resume", ""),
        "links": [{"url": link, "label": "synthetic"} for link in case.get("links", [])],
    }
    system, task, _version, _manifest = build_instructions(
        "prepare_questions",
        source_packet,
        config={"max_questions": 8, "max_featured_projects": 5},
        output_language="en",
    )
    return f"{system}\n\n{task}"


async def _run_case(
    adapter: OpenCodeGoAdapter,
    case: dict[str, Any],
    case_index: int,
) -> dict[str, Any]:
    start = time.monotonic()
    outcome: dict[str, Any] = {
        "case": case["name"],
        "case_index": case_index,
        "valid_json": False,
        "schema_pass": False,
        "semantic_pass": False,
        "empty": False,
        "truncated": False,
        "latency_ms": 0.0,
        "input_tokens": 0,
        "output_tokens": 0,
        "finish_reason": "unknown",
        "error_code": None,
    }
    try:
        result = await adapter.generate_structured(
            operation="prepare_questions",
            instructions=_synthetic_instructions(case),
            input_payload={"synthetic": True, "name": case["name"]},
            output_model=DiscoveryAnalysisResult,
        )
        outcome["latency_ms"] = round(result.latency_ms, 1)
        outcome["finish_reason"] = result.finish_reason or "unknown"
        outcome["input_tokens"] = int(result.usage.get("prompt_tokens", 0))
        outcome["output_tokens"] = int(result.usage.get("completion_tokens", 0))
        outcome["valid_json"] = True
        try:
            parsed = DiscoveryAnalysisResult.model_validate(result.parsed_output)
            outcome["schema_pass"] = True
            from oryxenai.agents.discovery.validators import validate_call_a_result

            validation = validate_call_a_result(
                parsed,
                {
                    "main_prompt": case.get("prompt", ""),
                    "resume_text": case.get("resume", ""),
                },
                get_settings().discovery,
            )
            outcome["semantic_pass"] = validation.is_valid
            outcome["semantic_errors"] = validation.errors[:5]
            outcome["fact_count"] = len(parsed.facts)
            outcome["question_count"] = len(parsed.questions)
            outcome["conflict_count"] = len(parsed.conflicts)
            outcome["unsupported_metric_count"] = parsed.quality_checks.unsupported_metric_count
        except Exception:
            outcome["schema_pass"] = False
    except Exception as exc:
        code = getattr(exc, "code", type(exc).__name__)
        outcome["error_code"] = code
        outcome["empty"] = code == "MODEL_EMPTY_OUTPUT"
        outcome["truncated"] = code == "MODEL_OUTPUT_TRUNCATED"
    finally:
        if outcome["latency_ms"] == 0.0:
            outcome["latency_ms"] = round((time.monotonic() - start) * 1000.0, 1)
    return outcome


async def _evaluate(profile: Any, label: str, num_cases: int) -> dict[str, Any]:
    adapter = OpenCodeGoAdapter(profile)
    results: list[dict[str, Any]] = []
    for index, case in enumerate(_SYNTHETIC_CASES[:num_cases]):
        results.append(await _run_case(adapter, case, index))
    if adapter._client is not None:
        await adapter._client.close()

    latencies = [r["latency_ms"] for r in results]
    summary = {
        "profile": label,
        "model": profile.model,
        "cases": len(results),
        "valid_json_rate": round(sum(1 for r in results if r["valid_json"]) / len(results), 3),
        "schema_pass_rate": round(sum(1 for r in results if r["schema_pass"]) / len(results), 3),
        "semantic_pass_rate": round(
            sum(1 for r in results if r["semantic_pass"]) / len(results), 3
        ),
        "empty_rate": round(sum(1 for r in results if r["empty"]) / len(results), 3),
        "truncation_rate": round(sum(1 for r in results if r["truncated"]) / len(results), 3),
        "median_latency_ms": round(statistics.median(latencies), 1) if latencies else 0.0,
        "p95_latency_ms": (
            round(sorted(latencies)[int(len(latencies) * 0.95) - 1], 1)
            if len(latencies) >= 20
            else None
        ),
        "mean_input_tokens": round(statistics.mean(r["input_tokens"] for r in results), 1),
        "mean_output_tokens": round(statistics.mean(r["output_tokens"] for r in results), 1),
        "error_codes": sorted({r["error_code"] for r in results if r["error_code"]}),
        "results": results,
    }
    return summary


async def main() -> None:
    parser = argparse.ArgumentParser(description="Live Discovery provider evaluation")
    parser.add_argument("--cases", type=int, default=15, help="Number of synthetic cases")
    parser.add_argument("--thinking", action="store_true", help="Run the thinking-enabled profile")
    args = parser.parse_args()

    if os.environ.get("RUN_LIVE_DISCOVERY") != "1":
        print("Live evaluation disabled. Set RUN_LIVE_DISCOVERY=1 to run.")
        return
    get_settings()
    if not os.environ.get("OPENCODE_GO_API_KEY"):
        print("No OPENCODE_GO_API_KEY found. Aborting.")
        return

    _REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%SZ")
    report: dict[str, Any] = {"generated_at": stamp, "profiles": {}}

    print(f"Running {args.cases} synthetic cases, thinking-disabled profile...")
    report["profiles"]["thinking_disabled"] = await _evaluate(
        _build_profile(reasoning_effort=""), "thinking_disabled", args.cases
    )

    if args.thinking:
        print("Running thinking-enabled profile...")
        report["profiles"]["thinking_enabled"] = await _evaluate(
            _build_profile(reasoning_effort="high"), "thinking_enabled", args.cases
        )

    out_path = _REPORTS_DIR / f"{stamp}.json"
    out_path.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    for label, summary in report["profiles"].items():
        print(
            f"[{label}] valid_json={summary['valid_json_rate']} "
            f"schema={summary['schema_pass_rate']} semantic={summary['semantic_pass_rate']} "
            f"empty={summary['empty_rate']} truncated={summary['truncation_rate']} "
            f"median_latency={summary['median_latency_ms']}ms "
            f"errors={summary['error_codes']}"
        )
    print(f"Report written to {out_path}")


if __name__ == "__main__":
    asyncio.run(main())
